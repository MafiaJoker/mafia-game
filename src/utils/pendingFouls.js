import { reactive } from 'vue'

// Отправленные, но ещё не подтверждённые сервером фолы одной игры.
//
// Одного и того же игрока рендерят два бейджа сразу — в колонке «Фолы» таблицы
// и в панели фолов диалога голосования. Пока свой pendingFouls был у каждого,
// они не видели отправленных значений друг друга: клик в панели показывал 2,
// таблица под диалогом продолжала показывать 1, а следующий клик по бейджу
// таблицы считался от ещё не обновлённых фолов игрока и отправлял ту же
// двойку — два клика давали один фол. Общее хранилище убирает расхождение
// и заодно даёт бейджам одного игрока сквозную нумерацию запросов.
export const createPendingFouls = () => {
  // `${box_id}-${type}` -> отправленное значение
  const counts = reactive({})
  // `${box_id}-${type}` -> номер последнего запроса: ответы прежних устарели
  const lastRequests = {}
  let requestSeq = 0

  const keyOf = (boxId, type) => `${boxId}-${type}`

  return {
    get: (boxId, type) => counts[keyOf(boxId, type)],

    // Регистрирует отправку фола и отдаёт ручки для обработки ответа
    send(boxId, type, count) {
      const key = keyOf(boxId, type)
      counts[key] = count
      const seq = ++requestSeq
      lastRequests[key] = seq

      return {
        // По этому типу фола уже улетел запрос новее — ответ применять нельзя
        isStale: () => lastRequests[key] !== seq,
        // Значение отыграно: показываем то, что пришло с сервера
        settle: () => { delete counts[key] }
      }
    },

    // Смена круга: неподтверждённые значения прошлого круга больше не наши
    clear() {
      Object.keys(counts).forEach(key => delete counts[key])
    }
  }
}
